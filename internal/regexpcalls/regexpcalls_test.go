var update = flag.Bool("update", false, "write allowed.tsv with the counts of the files under Dirs")

// root is the root of the repository.
const root = "../.."

func TestCount(t *testing.T) {
	dir := t.TempDir()
	files := map[string]string{
		"a.go":      "package a\n\nimport \"regexp\"\n\nvar x = regexp.MustCompile(`a`)\n\nfunc f() { regexp.Compile(\"b\"); regexp.MatchString(\"c\", \"c\") }\n",
		"b.go":      "package a\n\n// regexp.MustCompile(`a`)\nvar s = \"regexp.MustCompile(`a`)\"\n",
		"c.go":      "package a\n\nimport re \"regexp\"\n\nvar y = re.MustCompilePOSIX(`a`)\n\nfunc g() string { return re.QuoteMeta(\"x\") }\n",
		"d.go":      "package a\n\ntype r struct{}\n\nfunc (r) MustCompile(string) {}\n\nvar regexp r\n\nfunc h() { regexp.MustCompile(\"a\") }\n",
		"a_test.go": "package a\n\nimport \"regexp\"\n\nvar z = regexp.MustCompile(`a`)\n",
		"gen.go":    "// Code generated by x; DO NOT EDIT.\n\npackage a\n\nimport \"regexp\"\n\nvar w = regexp.MustCompile(`a`)\n",
		"data.txt":  "regexp.MustCompile(`a`)\n",
	}
	var names []string
	for n, src := range files {
		if err := os.WriteFile(filepath.Join(dir, n), []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
		names = append(names, n)
	}
	slices.Sort(names)
	got, err := Count(dir, names)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]int{"a.go": 3, "c.go": 1}
	if !maps.Equal(got, want) {
		t.Errorf("got %v, want %v", got, want)
	}
}

func TestAllowedRoundTrip(t *testing.T) {
	n := map[string]int{"a/b.go": 2, "c.go": 1}
	got, err := ParseAllowed(FormatAllowed(n))
	if err != nil || !maps.Equal(got, n) {
		t.Errorf("got %v, %v", got, err)
	}
	for _, bad := range []string{"", "path\tcount\na.go\t0\n", "path\tcount\na.go\t1\na.go\t1\n", "path\tcount\na.go\n"} {
		if _, err := ParseAllowed([]byte(bad)); err == nil {
			t.Errorf("%q: no error", bad)
		}
	}
}

func TestGrown(t *testing.T) {
	for _, c := range []struct {
		name      string
		base, now map[string]int
		want      []string
	}{
		{"same", map[string]int{"a.go": 2}, map[string]int{"a.go": 2}, nil},
		{"fewer", map[string]int{"a.go": 2, "b.go": 1}, map[string]int{"a.go": 1}, nil},
		{"more", map[string]int{"a.go": 2}, map[string]int{"a.go": 3}, []string{"a.go"}},
		{"a new file", map[string]int{"a.go": 2}, map[string]int{"a.go": 2, "b.go": 1}, []string{"b.go"}},
		{"no base", nil, map[string]int{"a.go": 2}, nil},
	} {
		if got := Grown(c.base, c.now); !slices.Equal(got, c.want) {
			t.Errorf("%s: %v, want %v", c.name, got, c.want)
		}
	}
}

// TestAllowed: the regexp calls of the code tree are, file by file, as
// many as allowed.tsv allows (go test -update writes it). A new one fails;
// so does one removed, until allowed.tsv says so.
func TestAllowed(t *testing.T) {
	files, err := Files(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) < 1000 {
		t.Fatalf("%d files in the code tree", len(files))
	}
	now, err := Count(root, files)
	if err != nil {
		t.Fatal(err)
	}
	if *update {
		if err := os.WriteFile("allowed.tsv", FormatAllowed(now), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	b, err := os.ReadFile("allowed.tsv")
	if err != nil {
		t.Fatal(err)
	}
	allowed, err := ParseAllowed(b)
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range slices.Sorted(maps.Keys(union(now, allowed))) {
		if now[p] != allowed[p] {
			t.Errorf("%s: %d regexp calls, allowed.tsv allows %d (read ${{ }} with actions/expr and scripts with actions/shell; go test -update after removing one)", p, now[p], allowed[p])
		}
	}
}

func union(a, b map[string]int) map[string]int {
	u := maps.Clone(a)
	for p, n := range b {
		u[p] = max(u[p], n)
	}
	return u
}

// TestNoGrowth: allowed.tsv allows no more than it does at the merge base
// of the branch with main. It needs git and a main.
func TestNoGrowth(t *testing.T) {
	base, err := exec.Command("git", "merge-base", "HEAD", "main").Output()
	if err != nil {
		t.Skipf("no merge base with main: %v", err)
	}
	old, err := exec.Command("git", "show", strings.TrimSpace(string(base))+":internal/regexpcalls/allowed.tsv").Output()
	if err != nil {
		t.Skipf("main has no allowed.tsv yet: %v", err)
	}
	was, err := ParseAllowed(old)
	if err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile("allowed.tsv")
	if err != nil {
		t.Fatal(err)
	}
	now, err := ParseAllowed(b)
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range Grown(was, now) {
		t.Errorf("%s: allowed.tsv allows %d regexp calls, more than the %d of main: write it without them", p, now[p], was[p])
	}
}
