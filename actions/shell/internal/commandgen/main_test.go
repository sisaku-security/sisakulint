func TestUpToDate(t *testing.T) {
	data, err := os.ReadFile("../../commands.json")
	if err != nil {
		t.Fatal(err)
	}
	schema, err := os.ReadFile("../../schema/commands.json")
	if err != nil {
		t.Fatal(err)
	}
	want, err := Generate(data, schema)
	if err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile("../../commands_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Error("commands_gen.go is not up to date; run go generate ./actions/shell/")
	}
}

const src = `{"citation": "https://example.com/a", "text": "t", "language": "en", "retrieved": "2026-10-11"}`

func TestGenerateShape(t *testing.T) {
	schema, err := os.ReadFile("../../schema/commands.json")
	if err != nil {
		t.Fatal(err)
	}
	out, err := Generate([]byte(`{"commands": [
		{"names": ["python"], "name_pattern": "python[0-9.]*", "options": [{"spellings": ["-c"], "value": true, "reading": "code", "cluster": true, "joined": true}], "traits": ["code-stdin"], "sources": [`+src+`]},
		{"names": ["timeout"], "operands": 1, "traits": ["runs-operand"], "sources": [`+src+`]},
		{"names": ["git"], "traits": [], "sources": [`+src+`]},
		{"names": ["git"], "subcommand": ["push"], "traits": ["writes-with-token"], "sources": [], "unsourced": "u"}
	]}`), schema)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"// Code generated by commandgen from commands.json; DO NOT EDIT.",
		`{Names: []string{"python"}, Pattern: regexp.MustCompile("^(?:python[0-9.]*)$"), Options: []CommandOption{{Spellings: []string{"-c"}, Value: true, Reading: ArgumentReadingCode, Cluster: true, Joined: true}}, Traits: []CommandTrait{CommandTraitCodeStdin}},`,
		`{Names: []string{"timeout"}, Operands: 1, Traits: []CommandTrait{CommandTraitRunsOperand}},`,
		`{Names: []string{"git"}},`,
		`{Names: []string{"git"}, Subcommand: []string{"push"}, Traits: []CommandTrait{CommandTraitWritesWithToken}},`,
	} {
		if !strings.Contains(string(out), want) {
			t.Errorf("no %s in\n%s", want, out)
		}
	}
}

func TestCheckRejects(t *testing.T) {
	schema, err := os.ReadFile("../../schema/commands.json")
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range []struct{ name, entries, want string }{
		{"no names", `{"names": [], "traits": [], "sources": [` + src + `]}`, "no names"},
		{"no sources and no unsourced", `{"names": ["a"], "traits": [], "sources": []}`, "no sources"},
		{"twice", `{"names": ["a"], "traits": [], "sources": [` + src + `]}, {"names": ["a"], "traits": [], "sources": [` + src + `]}`, "twice"},
		{"a subcommand without its parent", `{"names": ["a"], "subcommand": ["b"], "traits": [], "sources": [` + src + `]}`, "parent"},
		{"cluster on a long option", `{"names": ["a"], "options": [{"spellings": ["--x"], "cluster": true}], "traits": [], "sources": [` + src + `]}`, "cluster"},
		{"a reading without a value", `{"names": ["a"], "options": [{"spellings": ["-x"], "reading": "code"}], "traits": [], "sources": [` + src + `]}`, "value"},
		{"operands of no wrapper", `{"names": ["a"], "operands": 1, "traits": [], "sources": [` + src + `]}`, "runs-operand"},
		{"a pattern Go does not read", `{"names": ["a"], "name_pattern": "(", "traits": [], "sources": [` + src + `]}`, "name_pattern"},
		{"a trait twice", `{"names": ["a"], "traits": ["code-stdin", "code-stdin"], "sources": [` + src + `]}`, "twice"},
		{"a key the schema does not have", `{"names": ["a"], "traits": [], "sources": [` + src + `], "extra": 1}`, "extra"},
		{"a one-word attack without joined", `{"names": ["a"], "options": [{"spellings": ["-x"], "value": true, "reading": "code", "attack": ["with-blanks"]}], "traits": [], "sources": [` + src + `]}`, "joins it"},
		{"a trait the schema does not have", `{"names": ["a"], "traits": ["safe"], "sources": [` + src + `]}`, "traits/0"},
	} {
		t.Run(c.name, func(t *testing.T) {
			_, err := Generate([]byte(`{"commands": [`+c.entries+`]}`), schema)
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Errorf("error = %v, want it to mention %q", err, c.want)
			}
		})
	}
}
