// Command commandgen writes commands_gen.go, the entries of the commands
// actions/shell knows, from commands.json. It checks the file against
// schema/commands.json, and against what the schema does not say: each entry
// has a name, and a source or why it has none; the entry of a subcommand
// comes after its parent's; no name has two entries of the same subcommand;
// cluster is only on an option of one letter (-x, or +x); an option with a
// reading takes a value; an attack spelling seen to run in one word is of an
// option whose value joins it, and two-words of one that takes the next word
// (one seen not to run in one word may be of any option); remote is only on
// an option with an attack spelling; a request reading is of an option with a
// value; operands and assignments are only on a runs-operand entry; a
// name_pattern is a Go regexp. Run it with go generate in actions/shell.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"slices"
	"strings"

	"github.com/gh-intel/sisakulint/actions/internal/ident"
	"github.com/gh-intel/sisakulint/actions/internal/jsonschema"
)

func main() {
	data, err := os.ReadFile("commands.json")
	if err != nil {
		log.Fatal(err)
	}
	schema, err := os.ReadFile("schema/commands.json")
	if err != nil {
		log.Fatal(err)
	}
	b, err := Generate(data, schema)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("commands_gen.go", b, 0o644); err != nil {
		log.Fatal(err)
	}
}

type file struct {
	Commands []entry `json:"commands"`
}

type entry struct {
	Names                []string          `json:"names"`
	NamePattern          string            `json:"name_pattern"`
	Subcommand           []string          `json:"subcommand"`
	Options              []option          `json:"options"`
	Operands             int               `json:"operands"`
	Assignments          bool              `json:"assignments"`
	OptionsAfterOperands bool              `json:"options_after_operands"`
	OperandsOnly         bool              `json:"operands_only"`
	OperandRequest       string            `json:"operand_request"`
	ValueReading         string            `json:"value_reading"`
	InputValueCode       bool              `json:"input_value_code"`
	ValueOptionsComplete bool              `json:"value_options_complete"`
	LongOptionPrefixes   []string          `json:"long_option_prefixes"`
	Traits               []string          `json:"traits"`
	Sources              []json.RawMessage `json:"sources"`
	Unsourced            string            `json:"unsourced"`
}

type option struct {
	Spellings    []string `json:"spellings"`
	Value        bool     `json:"value"`
	Reading      string   `json:"reading"`
	Cluster      bool     `json:"cluster"`
	Joined       bool     `json:"joined"`
	Attack       []string `json:"attack"`
	Harmless     []string `json:"harmless"`
	Remote       bool     `json:"remote"`
	EndsOptions  bool     `json:"ends_options"`
	Request      string   `json:"request"`
	ValueReading string   `json:"value_reading"`
}

// schemaName is the name the schema is loaded by.
const schemaName = "commands-schema.json"

// Generate makes commands_gen.go from commands.json (data) and
// schema/commands.json (schema).
func Generate(data, schema []byte) ([]byte, error) {
	set, err := jsonschema.Load(map[string][]byte{schemaName: schema}, jsonschema.Options{})
	if err != nil {
		return nil, err
	}
	if err := set.Validate(schemaName, "#", data); err != nil {
		return nil, err
	}
	var f file
	if err := json.Unmarshal(data, &f); err != nil {
		return nil, err
	}
	if err := check(f.Commands); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by commandgen from commands.json; DO NOT EDIT.\n\npackage shell\n\n")
	if slices.ContainsFunc(f.Commands, func(e entry) bool { return e.NamePattern != "" }) {
		b.WriteString("import \"regexp\"\n\n")
	}
	b.WriteString("var commandEntries = []CommandEntry{\n")
	for _, e := range f.Commands {
		b.WriteString(literal(e) + ",\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func check(es []entry) error {
	seen := map[string]bool{}
	key := func(n string, sub []string) string { return n + " " + strings.Join(sub, " ") }
	for i, e := range es {
		at := fmt.Sprintf("commands[%d] (%s)", i, strings.Join(append(slices.Clone(e.Names), e.Subcommand...), " "))
		if len(e.Names) == 0 {
			return fmt.Errorf("%s: no names", at)
		}
		if len(e.Sources) == 0 && e.Unsourced == "" {
			return fmt.Errorf("%s: no sources and no unsourced", at)
		}
		if e.NamePattern != "" {
			if _, err := regexp.Compile(e.NamePattern); err != nil {
				return fmt.Errorf("%s: name_pattern: %v", at, err)
			}
		}
		for _, n := range e.Names {
			if seen[key(n, e.Subcommand)] {
				return fmt.Errorf("%s: %s is there twice", at, key(n, e.Subcommand))
			}
			if len(e.Subcommand) > 0 && !seen[key(n, e.Subcommand[:len(e.Subcommand)-1])] {
				return fmt.Errorf("%s: no parent entry before it", at)
			}
			seen[key(n, e.Subcommand)] = true
		}
		for _, o := range e.Options {
			if len(o.Spellings) == 0 {
				return fmt.Errorf("%s: an option without spellings", at)
			}
			for _, s := range o.Spellings {
				if o.Cluster && (len(s) != 2 || s[0] != '-' && s[0] != '+' || s[1] == '-' || s[1] == '+') {
					return fmt.Errorf("%s: %s: cluster is for an option of one letter", at, s)
				}
			}
			if o.Reading != "" && !o.Value && !o.Joined {
				return fmt.Errorf("%s: %s: a reading needs a value", at, o.Spellings[0])
			}
			for _, a := range append(slices.Clone(o.Attack), o.Harmless...) {
				switch {
				case a == "two-words" && !o.Value:
					return fmt.Errorf("%s: %s: two-words is of an option that takes the next word", at, o.Spellings[0])
				case a != "two-words" && !o.Joined && slices.Contains(o.Attack, a):
					// a spelling seen to run in one word needs the value joined to
					// the option; one seen not to run is an observation of any option
					return fmt.Errorf("%s: %s: %s is of an option whose value joins it", at, o.Spellings[0], a)
				case slices.Contains(o.Attack, a) && slices.Contains(o.Harmless, a):
					return fmt.Errorf("%s: %s: %s both runs and does not", at, o.Spellings[0], a)
				}
			}
			if o.EndsOptions && !o.Value {
				return fmt.Errorf("%s: %s: ends_options is of an option with a value", at, o.Spellings[0])
			}
			if o.Request != "" && !o.Value && !o.Joined {
				return fmt.Errorf("%s: %s: a request reading needs a value", at, o.Spellings[0])
			}
			if o.ValueReading != "" && !o.Value && !o.Joined {
				return fmt.Errorf("%s: %s: a value reading needs a value", at, o.Spellings[0])
			}
			if o.Remote && len(o.Attack) == 0 {
				return fmt.Errorf("%s: %s: remote is of an option with an attack spelling", at, o.Spellings[0])
			}
		}
		if (e.Operands != 0 || e.Assignments) && !slices.Contains(e.Traits, "runs-operand") {
			return fmt.Errorf("%s: operands and assignments are for a runs-operand entry", at)
		}
		for j, t := range e.Traits {
			if slices.Contains(e.Traits[:j], t) {
				return fmt.Errorf("%s: %s is there twice", at, t)
			}
		}
	}
	return nil
}

// literal is e as a Go composite literal of a CommandEntry; fields at their
// zero value are left out.
func literal(e entry) string {
	var f []string
	f = append(f, "Names: "+strs(e.Names))
	if e.NamePattern != "" {
		f = append(f, fmt.Sprintf("Pattern: regexp.MustCompile(%q)", "^(?:"+e.NamePattern+")$"))
	}
	if len(e.Subcommand) > 0 {
		f = append(f, "Subcommand: "+strs(e.Subcommand))
	}
	if len(e.Options) > 0 {
		var opts []string
		for _, o := range e.Options {
			g := []string{"Spellings: " + strs(o.Spellings)}
			if o.Value {
				g = append(g, "Value: true")
			}
			if o.Reading != "" {
				g = append(g, "Reading: ArgumentReading"+ident.GoName(o.Reading))
			}
			if o.Cluster {
				g = append(g, "Cluster: true")
			}
			if o.Joined {
				g = append(g, "Joined: true")
			}
			if len(o.Attack) > 0 {
				var as []string
				for _, a := range o.Attack {
					as = append(as, "AttackSpelling"+ident.GoName(a))
				}
				g = append(g, "Attack: []AttackSpelling{"+strings.Join(as, ", ")+"}")
			}
			if len(o.Harmless) > 0 {
				var hs []string
				for _, a := range o.Harmless {
					hs = append(hs, "AttackSpelling"+ident.GoName(a))
				}
				g = append(g, "Harmless: []AttackSpelling{"+strings.Join(hs, ", ")+"}")
			}
			if o.Remote {
				g = append(g, "Remote: true")
			}
			if o.EndsOptions {
				g = append(g, "EndsOptions: true")
			}
			if o.Request != "" {
				g = append(g, "Request: RequestReading"+ident.GoName(o.Request))
			}
			if o.ValueReading != "" {
				g = append(g, "ValueReading: CodeReading"+ident.GoName(o.ValueReading))
			}
			opts = append(opts, "{"+strings.Join(g, ", ")+"}")
		}
		f = append(f, "Options: []CommandOption{"+strings.Join(opts, ", ")+"}")
	}
	if e.Operands != 0 {
		f = append(f, fmt.Sprintf("Operands: %d", e.Operands))
	}
	if e.Assignments {
		f = append(f, "Assignments: true")
	}
	if e.OptionsAfterOperands {
		f = append(f, "OptionsAfterOperands: true")
	}
	if e.OperandsOnly {
		f = append(f, "OperandsOnly: true")
	}
	if e.ValueOptionsComplete {
		f = append(f, "ValueOptionsComplete: true")
	}
	if len(e.LongOptionPrefixes) > 0 {
		f = append(f, fmt.Sprintf("LongOptionPrefixes: %#v", e.LongOptionPrefixes))
	}
	if e.OperandRequest != "" {
		f = append(f, "OperandRequest: RequestReading"+ident.GoName(e.OperandRequest))
	}
	if e.ValueReading != "" {
		f = append(f, "ValueReading: CodeReading"+ident.GoName(e.ValueReading))
	}
	if e.InputValueCode {
		f = append(f, "InputValueCode: true")
	}
	if len(e.Traits) > 0 {
		var ts []string
		for _, t := range e.Traits {
			ts = append(ts, "CommandTrait"+ident.GoName(t))
		}
		f = append(f, "Traits: []CommandTrait{"+strings.Join(ts, ", ")+"}")
	}
	return "{" + strings.Join(f, ", ") + "}"
}

func strs(ss []string) string {
	var q []string
	for _, s := range ss {
		q = append(q, fmt.Sprintf("%q", s))
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}
