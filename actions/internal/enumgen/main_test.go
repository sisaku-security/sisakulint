// TestGenerateOnlyTheGiven: a schema that is only reached by $ref gives
// no types.
func TestGenerateOnlyTheGiven(t *testing.T) {
	files := map[string][]byte{
		"s.json": []byte(`{"$defs": {"a": {"$ref": "t.json#/$defs/b"}}}`),
		"t.json": []byte(`{"$defs": {"b": {"oneOf": [{"const": "x", "description": "d"}]}}}`),
	}
	out, err := Generate("p", files, []string{"s.json"})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(out), "B = iota") {
		t.Errorf("a type of t.json:\n%s", out)
	}
}

// TestGenerateOnly: with only, the enumerations of those names alone are
// written, and a name no schema has is an error.
func TestGenerateOnly(t *testing.T) {
	files := map[string][]byte{"s.json": []byte(`{"$defs": {
		"a": {"oneOf": [{"const": "x", "description": "X."}]},
		"b": {"oneOf": [{"const": "y", "description": "Y."}]}}}`)}
	b, err := Generate("p", files, []string{"s.json"}, "b")
	if err != nil {
		t.Fatal(err)
	}
	if out := string(b); strings.Contains(out, "AX") || !strings.Contains(out, "BY") {
		t.Errorf("%s", out)
	}
	if _, err := Generate("p", files, []string{"s.json"}, "c"); err == nil {
		t.Error("no error for a name no schema has")
	}
}

