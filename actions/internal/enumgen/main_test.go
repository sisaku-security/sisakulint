// TestGenerateAxesTakesItemKeywords: minItems and uniqueItems on an axis
// change no Go type, and the generated file is the same.
func TestGenerateAxesTakesItemKeywords(t *testing.T) {
	const color = `"color": {"description": "A color.", "oneOf": [{"const": "red", "description": "Red."}]},`
	looks := func(extra string) string {
		return color + `"looks": {"description": "L.", "x-go-axes": "look", "type": "object", "properties": {"color": {"description": "C.", "type": "array", ` + extra + `"items": {"$ref": "#/$defs/color"}}}, "required": ["color"], "additionalProperties": false}`
	}
	plain, err := gen(t, looks(""))
	if err != nil {
		t.Fatal(err)
	}
	with, err := gen(t, looks(`"minItems": 1, "uniqueItems": true, `))
	if err != nil {
		t.Fatal(err)
	}
	if plain != with {
		t.Errorf("minItems and uniqueItems changed the generated file:\n%s\n---\n%s", plain, with)
	}
}
