// generated are the files go generate writes with enumgen: the package,
// the file, the schemas it generates from and the schemas their $ref
// reach, relative to actions/internal/enumgen.
var generated = []struct {
	pkg, out             string
	gen, ref, only, skip []string
}{
	{"lint", "../../lint/enum_gen.go", []string{"../../lint/schema/registry-v0.json", "../../lint/schema/report-v0.json"}, []string{"../../facts/schema/facts-v0.json"}, nil, []string{"no-fix-reason", "side-effect"}},
	{"facts", "../../facts/enum_gen.go", []string{"../../facts/schema/facts-v0.json"}, nil, nil, nil},
	{"ir", "../../ir/enum_gen.go", []string{"../../lint/schema/registry-v0.json", "../../lint/schema/report-v0.json"}, []string{"../../facts/schema/facts-v0.json"}, []string{"no-fix-reason", "side-effect"}, nil},
	{"shell", "../../shell/enum_gen.go", []string{"../../shell/schema/commands.json"}, nil, nil, nil},
}

func TestUpToDate(t *testing.T) {
	for _, g := range generated {
		files, order, err := load(g.gen, g.ref)
		if err != nil {
			t.Fatal(err)
		}
		want, err := generate(g.pkg, files, order, g.only, g.skip)
		if err != nil {
			t.Fatal(err)
		}
		got, err := os.ReadFile(g.out)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s is not up to date; run go generate ./actions/%s/", g.out, g.pkg)
		}
	}
}

func gen(t *testing.T, defs string) (string, error) {
	t.Helper()
	b, err := Generate("p", map[string][]byte{"s.json": []byte(`{"$defs": {` + defs + `}}`)}, []string{"s.json"})
	return string(b), err
}

func TestGenerateShape(t *testing.T) {
	out, err := gen(t, `
		"fork-kind": {"oneOf": [
			{"const": "fork-pr-author", "description": "The author of a pull request from a fork."},
			{"const": "n", "description": "N."},
			{"const": "local_only", "description": "A value of the REST API, in snake_case."}
		]},
		"letter": {"description": "A letter.", "oneOf": [{"const": "N", "x-name": "network", "description": "Network."}, {"const": "AV", "x-name": "attack-vector", "description": "Attack Vector."}]},
		"state": {"x-go-zero": "unknown", "oneOf": [
			{"const": "resolved", "description": "Known."},
			{"const": "unknown", "description": "Not known."}
		]},
		"union": {"oneOf": [{"$ref": "#/$defs/letter"}, {"type": "object"}]}`)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"// Code generated by enumgen from s.json; DO NOT EDIT.",
		"package p",
		// in the order of the schema, with the description as the doc
		"\tForkKindUnset ForkKind = iota\n\t// ForkKindForkPRAuthor: The author of a pull request from a fork.\n\tForkKindForkPRAuthor\n\t// ForkKindN: N.\n\tForkKindN\n",
		`var forkKindNames = [...]string{"", "fork-pr-author", "n", "local_only"}`,
		// a value of the REST API in snake_case, its Go name as of kebab-case
		"\t// ForkKindLocalOnly: A value of the REST API, in snake_case.\n\tForkKindLocalOnly\n",
		"func ParseForkKind(s string) (ForkKind, error)",
		"func (v ForkKind) valid() bool { return v > 0 && int(v) < len(forkKindNames) }",
		// an abbreviation, as CVSS writes its values, named by its x-name
		"\t// LetterNetwork: Network.\n\tLetterNetwork\n\t// LetterAttackVector: Attack Vector.\n\tLetterAttackVector\n",
		`var letterNames = [...]string{"", "N", "AV"}`,
		// x-go-zero: that value is the zero one, and is valid
		"\t// StateUnknown: Not known.\n\tStateUnknown State = iota\n\t// StateResolved: Known.\n\tStateResolved\n",
		`var stateNames = [...]string{"unknown", "resolved"}`,
		"func (v State) valid() bool { return int(v) < len(stateNames) }",
		// Parse gives no value on an error, even where the zero one is a value
		"return ForkKindUnset, fmt.Errorf",
		"return State(len(stateNames)), fmt.Errorf",
		// the article of the name of what is not a value
		`is not a fork kind (fork-pr-author, n, local_only)`,
		`is not a letter (N, AV)`,
		// what each value is, as the schema says, and every value, for --explain=terms
		`var forkKindDescriptions = [...]string{"", "The author of a pull request from a fork.", "N.", "A value of the REST API, in snake_case."}`,
		"func (v ForkKind) description() string {",
		"func forkKindValues() []ForkKind {",
		`var stateDescriptions = [...]string{"Not known.", "Known."}`,
		// what the enumeration is, when the schema says
		`const letterDescription = "A letter."`,
	} {
		if !strings.Contains(out, want) {
			t.Errorf("the output has no\n%s\nin\n%s", want, out)
		}
	}
	for _, not := range []string{"StateUnset", "Union", "const forkKindDescription "} {
		if strings.Contains(out, not) {
			t.Errorf("the output has %s:\n%s", not, out)
		}
	}
}

func TestGenerateRejects(t *testing.T) {
	for _, c := range []struct{ name, defs, want string }{
		// jsonschema refuses it before enumgen sees it
		{"empty oneOf", `"a": {"oneOf": []}`, "non-empty"},
		{"x-go-zero on what is not an enumeration", `"a": {"x-go-zero": "x", "type": "string"}`, "x-go-zero"},
		{"two consts, one Go name", `"a": {"oneOf": [{"const": "n", "description": "d"}, {"const": "N", "x-name": "n", "description": "e"}]}`, "AN"},
		{"a kebab-case const and a snake_case const, one Go name", `"a": {"oneOf": [{"const": "local-only", "description": "d"}, {"const": "local_only", "description": "e"}]}`, "ALocalOnly"},
		{"a const named unset", `"a": {"oneOf": [{"const": "unset", "description": "d"}]}`, "AUnset"},
		{"a definition that takes no const", `"a": {"type": "integer", "oneOf": [{"const": "x", "description": "d"}]}`, "does not take"},
		{"no description", `"a": {"oneOf": [{"const": "x"}]}`, "description"},
		{"description on two lines", `"a": {"oneOf": [{"const": "x", "description": "d\ne"}]}`, "description"},
		{"not kebab-case", `"a": {"oneOf": [{"const": "A_b", "description": "d"}]}`, "kebab"},
		{"a capital and a letter", `"a": {"oneOf": [{"const": "Ab", "description": "d"}]}`, "kebab"},
		{"a letter and a capital", `"a": {"oneOf": [{"const": "aB", "description": "d"}]}`, "kebab"},
		{"an abbreviation without its name", `"a": {"oneOf": [{"const": "N", "description": "d"}]}`, "x-name"},
		{"a name of a word", `"a": {"oneOf": [{"const": "low", "x-name": "lowest", "description": "d"}]}`, "x-name"},
		{"a name not kebab-case", `"a": {"oneOf": [{"const": "N", "x-name": "Network", "description": "d"}]}`, "x-name"},
		{"a name not a string", `"a": {"oneOf": [{"const": "N", "x-name": 1, "description": "d"}]}`, "x-name"},
		{"another annotation", `"a": {"oneOf": [{"const": "x", "x-go-zero": "x", "description": "d"}]}`, "const"},
		{"not a string", `"a": {"oneOf": [{"const": 1, "description": "d"}]}`, "string"},
		{"twice", `"a": {"oneOf": [{"const": "x", "description": "d"}, {"const": "x", "description": "e"}]}`, "twice"},
		{"more than a const", `"a": {"oneOf": [{"const": "x", "description": "d", "type": "string"}]}`, "const"},
		{"a const and a $ref", `"a": {"oneOf": [{"const": "x", "description": "d"}, {"$ref": "#/$defs/b"}]}, "b": {"type": "string"}`, "const"},
		{"x-go-zero not a value", `"a": {"x-go-zero": "y", "oneOf": [{"const": "x", "description": "d"}]}`, "x-go-zero"},
		{"x-go-zero not a string", `"a": {"x-go-zero": 1, "oneOf": [{"const": "x", "description": "d"}]}`, "x-go-zero"},
		{"an item with minItems", `"a": {"oneOf": [{"const": "x", "description": "d", "minItems": 1}]}`, "const"},
		{"an item with uniqueItems", `"a": {"oneOf": [{"const": "x", "description": "d", "uniqueItems": true}]}`, "const"},
		{"an item with unevaluatedProperties", `"a": {"oneOf": [{"const": "x", "description": "d", "unevaluatedProperties": false}]}`, "const"},
		{"an item with an empty enum", `"a": {"oneOf": [{"const": "x", "description": "d", "enum": []}]}`, "const"},
	} {
		t.Run(c.name, func(t *testing.T) {
			_, err := gen(t, c.defs)
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Errorf("error = %v, want it to mention %q", err, c.want)
			}
		})
	}
}

