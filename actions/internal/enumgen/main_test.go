// TestGenerateAxes: a member with x-go-axes is a struct of a field of each
// property, in their order, of the enumeration its items refer to; the
// axis type named by x-go-axes is an enumeration of the names of those
// enumerations, with each one's description and its key; and Axes and
// the value of every value of each axis are generated, so that nothing in
// Go names an axis by hand.
func TestGenerateAxes(t *testing.T) {
	out, err := gen(t, `
		"color": {"description": "A color.", "oneOf": [{"const": "red", "description": "Red."}, {"const": "blue", "description": "Blue."}]},
		"pen-size": {"description": "The size of a pen.", "oneOf": [{"const": "fine", "description": "Fine."}]},
		"looks": {"description": "How a thing looks.", "x-go-axes": "look", "type": "object",
			"properties": {"color": {"description": "The color of a thing.", "type": "array", "items": {"$ref": "#/$defs/color"}}, "pen_size": {"description": "How fine the pen is.", "type": "array", "items": {"$ref": "#/$defs/pen-size"}}},
			"required": ["color", "pen_size"], "additionalProperties": false}`)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"// Looks is $defs/looks: How a thing looks.\ntype Looks struct {\n\tColor   []Color   `json:\"color\"`\n\tPenSize []PenSize `json:\"pen_size\"`\n}",
		"\tLookUnset Look = iota\n\t// LookColor: The color of a thing.\n\tLookColor\n\t// LookPenSize: How fine the pen is.\n\tLookPenSize\n",
		`var lookNames = [...]string{"", "color", "pen-size"}`,
		`var lookKeys = [...]string{"", "color", "pen_size"}`,
		"func (v Look) Key() string",
		"func (v Look) Description() string { return v.description() }",
		"func (v Color) Description() string { return v.description() }",
		"func (v PenSize) Description() string { return v.description() }",
		"type LookValue interface {",
		"type LookAxis struct {\n\tLook   Look\n\tValues []LookValue\n}",
		"func (x Looks) Axes() []LookAxis {\n\treturn []LookAxis{\n\t\t{LookColor, lookValuesOf(x.Color)},\n\t\t{LookPenSize, lookValuesOf(x.PenSize)},\n\t}\n}",
		"func looksAll() Looks {\n\treturn Looks{Color: colorValues(), PenSize: penSizeValues()}\n}",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("the generated file has no\n%s\n---\n%s", want, out)
		}
	}
}

