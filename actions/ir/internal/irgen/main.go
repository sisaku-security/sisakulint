// Command irgen writes summary_gen.go of actions/ir from summaries.json
// and views.json: the enumerations Field and SummaryType; the value types
// and how two values are equal; each summary type, the fields in which two
// summaries differ, and which of them Diff compares; and for each view of
// views.json, its View, its reader, and for each summary type it reads, a
// type with the accessors of the fields and the operations it declares and
// nothing else. Run it with go generate in actions/ir.
//
// An operation's fields, those summaries.json says it reads, are part of
// the fields of each view that declares it. An operation calls the method
// of the summary type named as the operation with a lower-case first
// letter, written by hand, with the RuleAccess first. A field of a value type
// is compared by its method equal, a slice of a value type by
// slices.EqualFunc, any other slice by slices.Equal, and any other type by
// ==; compare false leaves a field out.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"github.com/sisaku-security/sisakulint/actions/internal/ident"
	"go/ast"
	"go/format"
	"go/parser"
	"log"
	"os"
	"regexp"
	"slices"
	"strings"
)

func main() {
	sin := flag.String("summaries", "summaries.json", "the definitions of the summary types")
	vin := flag.String("views", "views.json", "the definitions of the views")
	out := flag.String("out", "summary_gen.go", "the Go file to write")
	flag.Parse()
	s, err := os.ReadFile(*sin)
	if err != nil {
		log.Fatal(err)
	}
	v, err := os.ReadFile(*vin)
	if err != nil {
		log.Fatal(err)
	}
	b, err := Generate(s, v)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, b, 0o644); err != nil {
		log.Fatal(err)
	}
}

type definitions struct {
	Imports   []string  `json:"imports"`
	Values    []value   `json:"values"`
	Summaries []summary `json:"summaries"`
}

type value struct {
	Name   string  `json:"name"`
	Doc    string  `json:"doc"`
	Fields []field `json:"fields"`
}

type summary struct {
	Name    string   `json:"name"`
	List    string   `json:"list"`
	Slug    string   `json:"slug"`
	Doc     string   `json:"doc"`
	Handles []handle `json:"handles"`
	Fields  []field  `json:"fields"`
	Fixes   []op     `json:"fixes"`
}

type handle struct {
	Name string `json:"name"`
	Doc  string `json:"doc"`
}

type field struct {
	Name    string `json:"name"`
	Type    string `json:"type"`
	Doc     string `json:"doc"`
	Display bool   `json:"display"`
	Compare *bool  `json:"compare"`
}

type op struct {
	Name   string   `json:"name"`
	Params string   `json:"params"`
	Result string   `json:"result"`
	Doc    string   `json:"doc"`
	Reads  []string `json:"reads"`
	args   []string // the names of Params
}

type views struct {
	Views []view `json:"views"`
}

type view struct {
	Name   string   `json:"name"`
	Doc    string   `json:"doc"`
	Fields []string `json:"fields"`
	Fixes  []string `json:"fixes"`
}

var (
	unexported = regexp.MustCompile(`^[a-z][A-Za-z0-9]*$`)
	goName     = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9]*$`)
	typeName   = regexp.MustCompile(`^[A-Z][A-Za-z0-9]*$`)
	slugForm   = regexp.MustCompile(`^[a-z][a-z0-9]*(-[a-z0-9]+)*$`)
)

func decode(src []byte, v any) error {
	dec := json.NewDecoder(bytes.NewReader(src))
	dec.DisallowUnknownFields()
	return dec.Decode(v)
}

// Generate is the Go of the summary types src and the views vsrc.
func Generate(src, vsrc []byte) ([]byte, error) {
	var d definitions
	var vs views
	if err := decode(src, &d); err != nil {
		return nil, err
	}
	if err := decode(vsrc, &vs); err != nil {
		return nil, err
	}
	fields, err := check(&d, vs)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("// Code generated by irgen from summaries.json and views.json; DO NOT EDIT.\n\npackage ir\n\nimport (\n\t\"slices\"\n")
	if len(d.Imports) > 0 {
		w("\n")
	}
	for _, imp := range d.Imports {
		w("\t%q\n", imp)
	}
	w(")\n\nvar _ = slices.Equal[[]int]\n\n")

	w("// SummaryField is a field of a summary: what a view declares its rules read,\n// and what Diff compares before and after a fix.\ntype SummaryField uint8\n\nconst (\n\tfieldUnset SummaryField = iota\n")
	for _, s := range d.Summaries {
		for _, f := range s.Fields {
			w("\t%s // %s: %s\n", fieldConst(s, f), s.Slug+"."+kebab(f.Name), f.Doc)
		}
	}
	w("\tfieldCount\n)\n\nvar fieldNames = [...]string{\"\"")
	for _, s := range d.Summaries {
		for _, f := range s.Fields {
			w(", %q", s.Slug+"."+kebab(f.Name))
		}
	}
	w("}\n\nvar fieldDisplay = [...]bool{false")
	for _, s := range d.Summaries {
		for _, f := range s.Fields {
			w(", %t", f.Display)
		}
	}
	w("}\n\nvar fieldSummary = [...]SummaryType{summaryUnset")
	for _, s := range d.Summaries {
		for range s.Fields {
			w(", Summary%s", s.Name)
		}
	}
	w("}\n\nfunc (f SummaryField) String() string { return fieldNames[f] }\n\n")
	w("// Display is whether f is only for the text of a finding: Diff does not\n// compare it.\nfunc (f SummaryField) Display() bool { return fieldDisplay[f] }\n\n")
	w("// Summary is the summary type f is a field of.\nfunc (f SummaryField) Summary() SummaryType { return fieldSummary[f] }\n\n")

	w("// SummaryType is a type of summary.\ntype SummaryType uint8\n\nconst (\n\tsummaryUnset SummaryType = iota\n")
	for _, s := range d.Summaries {
		w("\tSummary%s\n", s.Name)
	}
	w("\tsummaryCount\n)\n\nvar summaryNames = [...]string{\"\"")
	for _, s := range d.Summaries {
		w(", %q", s.Slug)
	}
	w("}\n\nfunc (t SummaryType) String() string { return summaryNames[t] }\n\n")

	for _, v := range d.Values {
		w("// %s\ntype %s struct {\n", v.Doc, v.Name)
		for _, f := range v.Fields {
			w("\t%s %s // %s\n", f.Name, f.Type, f.Doc)
		}
		w("}\n\nfunc (x %s) equal(y %s) bool {\n\treturn true", v.Name, v.Name)
		for _, f := range v.Fields {
			if compared(f) {
				w(" &&\n\t\t%s", equalExpr(&d, f, "x."+f.Name, "y."+f.Name))
			}
		}
		w("\n}\n\n")
	}

	for _, s := range d.Summaries {
		w("// %s\ntype %s struct {\n\tkey Key\n", s.Doc, s.Name)
		for _, h := range s.Handles {
			w("\t%s Handle // %s\n", h.Name, h.Doc)
		}
		for _, f := range s.Fields {
			w("\t%s %s // %s\n", f.Name, f.Type, f.Doc)
		}
		w("}\n\n// diff is the fields of s whose value o does not have; a field only for\n// the text of a finding is not compared.\nfunc (s *%s) diff(o *%s) []SummaryField {\n\tvar out []SummaryField\n", s.Name, s.Name)
		for _, f := range s.Fields {
			if compared(f) && !f.Display {
				w("\tif !(%s) {\n\t\tout = append(out, %s)\n\t}\n", equalExpr(&d, f, "s."+f.Name, "o."+f.Name), fieldConst(s, f))
			}
		}
		w("\treturn out\n}\n\n")
		w("func (s *%s) summaryKey() Key { return s.key }\n\n", s.Name)
		w("func (s *%s) summaryHandles() []Handle { return []Handle{", s.Name)
		for _, h := range s.Handles {
			w("s.%s, ", h.Name)
		}
		w("} }\n\n")
	}
	w("// changesOf are the summaries of type t that differ between before and\n// after, with the fields of each that are compared (Diff).\nfunc changesOf(before, after *IR, t SummaryType) []ChangedSummary {\n\tswitch t {\n")
	for _, s := range d.Summaries {
		var cmp []string
		for _, f := range s.Fields {
			if compared(f) && !f.Display {
				cmp = append(cmp, fieldConst(s, f))
			}
		}
		if len(cmp) == 0 {
			continue // nothing to compare (StepFix), and nothing is made
		}
		w("\tcase Summary%s:\n\t\treturn pair(before.all%s(), after.all%s(), []SummaryField{%s})\n", s.Name, s.List, s.List, strings.Join(cmp, ", "))
	}
	w("\t}\n\treturn nil\n}\n\n")

	for _, v := range vs.Views {
		read := fields[v.Name]
		w("// %sView is %s It has the fields its rules read, those of the\n// operations they use among them, and makes their reader.\nvar %sView = View[%sReader]{\n\tfields: []SummaryField{", v.Name, strings.TrimPrefix(v.Doc, v.Name+" is "), v.Name, v.Name)
		for _, f := range read.all {
			w("%s, ", f)
		}
		w("},\n\tmake: func(q *RuleAccess) %sReader { return %sReader{q} },\n}\n\n", v.Name, v.Name)
		w("// %sReader has the summaries of the input for the rules of %sView.\ntype %sReader struct{ q *RuleAccess }\n\n", v.Name, v.Name, v.Name)
		for _, s := range d.Summaries {
			if !read.summaries[s.Name] {
				continue
			}
			t := v.Name + "Of" + s.Name
			w("// %s are the %s summaries of the input, made the first time they are\n// asked for.\nfunc (r %sReader) %s() []%s {\n\tall := r.q.ir.all%s()\n\tout := make([]%s, len(all))\n\tfor i, s := range all {\n\t\tout[i] = %s{r.q, s}\n\t}\n\treturn out\n}\n\n", s.List, s.Name, v.Name, s.List, t, s.List, t, t)
			w("// %s is a %s as the rules of %sView read it.\ntype %s struct {\n\tq *RuleAccess\n\ts *%s\n}\n\n", t, s.Name, v.Name, t, s.Name)
			w("// Key is where the summary is.\nfunc (x %s) Key() Key { return x.s.key }\n\n", t)
			for _, h := range s.Handles {
				w("// %s is the handle on %s.\nfunc (x %s) %s() Handle { return x.s.%s }\n\n", exported(h.Name), h.Doc, t, exported(h.Name), h.Name)
			}
			for _, f := range s.Fields {
				if !slices.Contains(v.Fields, s.Slug+"."+kebab(f.Name)) {
					continue
				}
				w("// %s is %s.\nfunc (x %s) %s() %s { return x.s.%s }\n\n", exported(f.Name), f.Doc, t, exported(f.Name), f.Type, f.Name)
			}
			for _, o := range s.Fixes {
				if !slices.Contains(v.Fixes, s.Name+"."+o.Name) {
					continue
				}
				args := append([]string{"x.q"}, o.args...)
				w("// %s is %s.\nfunc (x %s) %s(%s) %s {\n", o.Name, o.Doc, t, o.Name, o.Params, o.Result)
				w("\treturn x.s.%s(%s)\n}\n\n", lowerFirst(o.Name), strings.Join(args, ", "))
			}
		}
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("the generated code does not format: %v", err)
	}
	return out, nil
}

// viewFields are the fields of a view: those it reads, then those its
// operations read, each once in the order of Field; and the summary types
// it reads.
type viewFields struct {
	all       []string // the Go constants
	summaries map[string]bool
}

// check checks the definitions, fills the names of the arguments of each
// operation, and gives the fields of each view.
func check(d *definitions, vs views) (map[string]viewFields, error) {
	var errs []error
	bad := func(format string, a ...any) { errs = append(errs, fmt.Errorf(format, a...)) }
	values := map[string]bool{}
	for _, v := range d.Values {
		if !typeName.MatchString(v.Name) || v.Doc == "" || values[v.Name] || len(v.Fields) == 0 {
			bad("value %q: a name used once, a doc and fields are needed", v.Name)
		}
		values[v.Name] = true
		seen := map[string]bool{}
		for _, f := range v.Fields {
			if !goName.MatchString(f.Name) || f.Type == "" || f.Doc == "" || seen[f.Name] {
				bad("%s: field %q: a name used once, a type and a doc are needed", v.Name, f.Name)
			}
			seen[f.Name] = true
		}
	}
	fieldOf := map[string]string{}   // <slug>.<kebab> → the Go constant
	summaryOf := map[string]string{} // <slug>.<kebab> → the summary type
	order := map[string]int{}        // the Go constant → its place in Field
	ops := map[string]op{}           // <Summary>.<op>
	opSummary := map[string]string{}
	summaries, lists, slugs := map[string]bool{}, map[string]bool{}, map[string]bool{}
	for _, s := range d.Summaries {
		if !typeName.MatchString(s.Name) || !typeName.MatchString(s.List) || !slugForm.MatchString(s.Slug) || s.Doc == "" || len(s.Fields) == 0 {
			bad("summary %q: a name, a list, a slug in kebab case, a doc and fields are needed", s.Name)
		}
		if summaries[s.Name] || lists[s.List] || slugs[s.Slug] {
			bad("summary %q: its name, list or slug is another's", s.Name)
		}
		summaries[s.Name], lists[s.List], slugs[s.Slug] = true, true, true
		names := map[string]bool{}
		for _, h := range s.Handles {
			if !unexported.MatchString(h.Name) || h.Doc == "" || names[h.Name] {
				bad("%s: handle %q: an unexported name used once and a doc are needed", s.Name, h.Name)
			}
			names[h.Name] = true
		}
		for _, f := range s.Fields {
			if !unexported.MatchString(f.Name) || f.Type == "" || f.Doc == "" || names[f.Name] {
				bad("%s: field %q: an unexported name used once, a type and a doc are needed", s.Name, f.Name)
			}
			names[f.Name] = true
			k := s.Slug + "." + kebab(f.Name)
			fieldOf[k], summaryOf[k] = fieldConst(s, f), s.Name
			order[fieldConst(s, f)] = len(order)
		}
	}
	for si := range d.Summaries {
		s := &d.Summaries[si]
		for oi := range s.Fixes {
			o := &s.Fixes[oi]
			if !typeName.MatchString(o.Name) || o.Result == "" || o.Doc == "" {
				bad("%s: op %q: a name, a result and a doc are needed", s.Name, o.Name)
			}
			for _, r := range o.Reads {
				if _, ok := fieldOf[r]; !ok {
					bad("%s.%s: it reads %q, which is not a field", s.Name, o.Name, r)
				}
			}
			args, err := argNames(o.Params)
			if err != nil {
				bad("%s.%s: params: %v", s.Name, o.Name, err)
			}
			o.args = args
			ops[s.Name+"."+o.Name], opSummary[s.Name+"."+o.Name] = *o, s.Name
		}
	}
	out := map[string]viewFields{}
	for _, v := range vs.Views {
		if !typeName.MatchString(v.Name) || !strings.HasPrefix(v.Doc, v.Name+" is ") {
			bad("view %q: a name and a doc that starts with it and is are needed", v.Name)
		}
		if _, ok := out[v.Name]; ok {
			bad("view %s twice", v.Name)
		}
		vf := viewFields{summaries: map[string]bool{}}
		consts := map[string]bool{}
		add := func(r string) {
			c, ok := fieldOf[r]
			if !ok {
				bad("view %s: %q is not a field", v.Name, r)
				return
			}
			consts[c] = true
			vf.summaries[summaryOf[r]] = true
		}
		seen := map[string]bool{}
		for _, r := range v.Fields {
			if seen[r] {
				bad("view %s: %q twice", v.Name, r)
			}
			seen[r] = true
			add(r)
		}
		for _, name := range v.Fixes {
			o, ok := ops[name]
			if !ok {
				bad("view %s: %q is not an operation of a summary type", v.Name, name)
				continue
			}
			vf.summaries[opSummary[name]] = true
			for _, r := range o.Reads {
				add(r)
			}
		}
		for c := range consts {
			vf.all = append(vf.all, c)
		}
		slices.SortFunc(vf.all, func(a, b string) int { return order[a] - order[b] })
		out[v.Name] = vf
	}
	return out, errors.Join(errs...)
}

// argNames are the names of the parameters params, such as ref and
// events of "ref int, events []analysis.EventActivity".
func argNames(params string) ([]string, error) {
	e, err := parser.ParseExpr("func(" + params + ")")
	if err != nil {
		return nil, err
	}
	var out []string
	for _, f := range e.(*ast.FuncType).Params.List {
		if len(f.Names) == 0 {
			return nil, errors.New("a parameter without a name")
		}
		for _, n := range f.Names {
			out = append(out, n.Name)
		}
	}
	return out, nil
}

func compared(f field) bool { return f.Compare == nil || *f.Compare }

// equalExpr is the Go of whether a and b, of the type of f, are equal.
func equalExpr(d *definitions, f field, a, b string) string {
	isValue := func(t string) bool {
		return slices.ContainsFunc(d.Values, func(v value) bool { return v.Name == t })
	}
	elem, slice := strings.CutPrefix(f.Type, "[]")
	switch {
	case slice && isValue(elem):
		return fmt.Sprintf("slices.EqualFunc(%s, %s, %s.equal)", a, b, elem)
	case slice:
		return fmt.Sprintf("slices.Equal(%s, %s)", a, b)
	case isValue(f.Type):
		return fmt.Sprintf("%s.equal(%s)", a, b)
	}
	return fmt.Sprintf("%s == %s", a, b)
}

func fieldConst(s summary, f field) string { return "Field" + s.Name + exported(f.Name) }

// exported is the Go name of name, a field of camelCase: its parts as
// ident.GoName writes them, with the initialisms in capitals (prCodeOn is
// PRCodeOn, sha is SHA).
func exported(name string) string { return ident.GoName(kebab(name)) }

func lowerFirst(name string) string { return strings.ToLower(name[:1]) + name[1:] }

// kebab is the name in a Field's text: stepPath is step-path.
func kebab(name string) string {
	var b strings.Builder
	for _, r := range name {
		if r >= 'A' && r <= 'Z' {
			b.WriteByte('-')
			r += 'a' - 'A'
		}
		b.WriteRune(r)
	}
	return b.String()
}
